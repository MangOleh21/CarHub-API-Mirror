CREATE TABLE cars (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  brand VARCHAR(100) NOT NULL,
  model VARCHAR(100) NOT NULL,
  year INT NOT NULL CHECK (year BETWEEN 1886 AND 2100),
  transmission VARCHAR(50) NOT NULL CHECK (transmission IN ('Manual', 'Automatic')),
  fuel_type VARCHAR(50) NOT NULL DEFAULT 'Bensin',
  mileage INT NOT NULL CHECK (mileage >= 0),
  price BIGINT NOT NULL CHECK (price > 0),
  image_url TEXT NOT NULL,
  seller_name VARCHAR(150) NOT NULL,
  seller_phone VARCHAR(50) NOT NULL,
  location VARCHAR(150) NOT NULL,
  description TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX cars_brand_idx ON cars (brand);
CREATE INDEX cars_price_idx ON cars (price);

CREATE TABLE submissions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  seller_name VARCHAR(150) NOT NULL,
  seller_phone VARCHAR(50) NOT NULL,
  brand VARCHAR(100) NOT NULL,
  model VARCHAR(100) NOT NULL,
  year INT NOT NULL CHECK (year BETWEEN 1886 AND 2100),
  transmission VARCHAR(50) NOT NULL CHECK (transmission IN ('Manual', 'Automatic')),
  mileage INT NOT NULL CHECK (mileage >= 0),
  expected_price BIGINT NOT NULL CHECK (expected_price > 0),
  image_url TEXT,
  description TEXT,
  status VARCHAR(20) NOT NULL DEFAULT 'pending'
    CHECK (status IN ('pending', 'approved', 'rejected')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX submissions_status_created_at_idx ON submissions (status, created_at DESC);

CREATE TABLE admin_users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email VARCHAR(254) NOT NULL,
  password_hash TEXT NOT NULL,
  role VARCHAR(20) NOT NULL CHECK (role IN ('owner', 'admin')),
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE UNIQUE INDEX admin_users_email_lower_idx ON admin_users (LOWER(email));

CREATE TABLE admin_sessions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  admin_user_id BIGINT NOT NULL REFERENCES admin_users(id) ON DELETE CASCADE,
  token_hash TEXT NOT NULL UNIQUE,
  expires_at TIMESTAMPTZ NOT NULL,
  revoked_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX admin_sessions_user_expiry_idx ON admin_sessions (admin_user_id, expires_at);
